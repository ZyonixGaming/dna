    function onLibraryDragStart(e) {
        const entryEl = e.target.closest('.gn-entry-item');
        const catEl = e.target.closest('.gn-cat-item');
        if (entryEl) drag = { kind: 'entry', id: entryEl.dataset.entry, fromCatId: entryEl.dataset.cat };
        else if (catEl) drag = { kind: 'cat', id: catEl.dataset.cat, fromCatId: null };
        else return;
        (entryEl || catEl).classList.add('dragging');
        if (e.dataTransfer) {
            e.dataTransfer.effectAllowed = 'move';
            
            try { e.dataTransfer.setData('text/plain', drag.id); } catch (err) {  }
        }
    }

    function onLibraryDragOver(e) {
        if (!drag) return;
        const entryEl = e.target.closest('.gn-entry-item');
        const catEl = e.target.closest('.gn-cat-item');
        const target = resolveDropTarget(entryEl, catEl);
        if (!target) return;
        e.preventDefault();                    
        if (e.dataTransfer) e.dataTransfer.dropEffect = 'move';
        clearMarkers();
        target.el.classList.add(target.mode);
    }

    
    function resolveDropTarget(entryEl, catEl) {
        if (!drag) return null;
        if (drag.kind === 'cat') {
            if (!catEl || catEl.dataset.cat === drag.id) return null;
            return { el: catEl, mode: 'drop-before', kind: 'cat' };
        }
        if (entryEl) {
            if (entryEl.dataset.entry === drag.id) return null;
            return { el: entryEl, mode: 'drop-before', kind: 'entry' };
        }
        if (catEl) {
            
            
            
            if (catEl.dataset.cat === drag.fromCatId) return null;
            return { el: catEl, mode: 'drop-into', kind: 'cat' };
        }
        return null;
    }

    function onLibraryDragLeave(e) {
        const row = e.target.closest && e.target.closest('.gn-entry-item, .gn-cat-item');
        
        
        if (row) row.classList.remove('drop-before', 'drop-into');
    }

    function onLibraryDrop(e) {
        if (!drag) return;
        const entryEl = e.target.closest('.gn-entry-item');
        const catEl = e.target.closest('.gn-cat-item');
        const target = resolveDropTarget(entryEl, catEl);
        e.preventDefault();
        const moved = drag;
        clearDragState();
        if (!target) return;

        let res = null;
        if (moved.kind === 'cat') {
            res = DnaLib.moveCategory(moved.id, target.el.dataset.cat);
            if (res) Toast.toast('Moved “' + res.name + '”', 'ok');
        } else if (target.kind === 'entry') {
            res = DnaLib.moveEntryBefore(moved.id, moved.fromCatId, target.el.dataset.cat, target.el.dataset.entry);
            if (res) {
                Toast.toast(res.sameCategory ? 'Moved “' + res.name + '”'
                    : 'Moved “' + res.name + '” to “' + res.to + '”', 'ok');
            }
        } else {
            res = DnaLib.moveEntryToCategory(moved.id, moved.fromCatId, target.el.dataset.cat);
            
            
            
            if (res) {
                selectedCategoryId = target.el.dataset.cat;
                Toast.toast('Moved “' + res.name + '” to “' + res.to + '”', 'ok');
            }
        }
        renderLibrary();
        renderCompareOptions();
    }

