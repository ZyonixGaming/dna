    function toggleFenceAt(wx, wy) {
        const nearestEdgeY = Math.round(wy / TILE_PX) * TILE_PX;
        const nearestEdgeX = Math.round(wx / TILE_PX) * TILE_PX;
        const distY = Math.abs(wy - nearestEdgeY), distX = Math.abs(wx - nearestEdgeX);
        if (distY > FENCE_BAND_PX && distX > FENCE_BAND_PX) return;
        let x, y, edge;
        if (distY <= distX) { x = Math.floor(wx / TILE_PX); y = Math.floor(nearestEdgeY / TILE_PX); edge = 'fenceT'; }
        else { x = Math.floor(nearestEdgeX / TILE_PX); y = Math.floor(wy / TILE_PX); edge = 'fenceL'; }
        if (!doc.grid.inBounds(x, y)) return;
        const rec = Object.assign({}, doc.grid.get(x, y));
        rec[edge] = !rec[edge];
        setTileWithUndo(x, y, rec);
    }

    
    
    
    function hitTestMarker(wx, wy) {
        if (overlays.locations) {
            for (const loc of mapSpaceMarkers()) {
                if (loc.value === 'Truck') continue;
                if (Math.abs(loc.x - wx) <= MARKER_HIT_RADIUS && Math.abs(loc.y - wy) <= MARKER_HIT_RADIUS) return { kind: 'location', obj: loc };
            }
            const vial = doc.state.locationMarkers.find((l) => l.value === 'vial world');
            if (vial) {
                const vEdit = doc.locationEdits.get(vial.offset);
                const vx = vEdit ? vEdit.x : vial.x, vy = vEdit ? vEdit.y : vial.y;
                const cx = vx + TILE_PX / 2, cy = vy + TILE_PX / 2;
                if (Math.abs(cx - wx) <= MARKER_HIT_RADIUS && Math.abs(cy - wy) <= MARKER_HIT_RADIUS) return { kind: 'vial', obj: Object.assign({}, vial, { x: vx, y: vy }) };
            }
            const truck = doc.state.locationMarkers.find((l) => l.value === 'Truck');
            if (truck) {
                const edit = doc.locationEdits.get(truck.offset);
                const tx = edit ? edit.x : truck.x, ty = edit ? edit.y : truck.y;
                if (Math.abs(tx - wx) <= MARKER_HIT_RADIUS && Math.abs(ty - wy) <= MARKER_HIT_RADIUS) return { kind: 'truck', obj: Object.assign({}, truck, { x: tx, y: ty }) };
            }
        }
        if (overlays.buried) {
            for (const b of doc.buriedItems) if (Math.abs(b.x - wx) <= MARKER_HIT_RADIUS && Math.abs(b.y - wy) <= MARKER_HIT_RADIUS) return { kind: 'buried', obj: b };
            
            
        }
        if (overlays.ground) {
            for (const g of activeItemsOfType(3)) if (Math.abs(g.x - wx) <= MARKER_HIT_RADIUS && Math.abs(g.y - wy) <= MARKER_HIT_RADIUS) return { kind: 'ground', obj: g };
        }
        if (overlays.holes) {
            for (const h of activeItemsOfType(4)) if (Math.abs(h.x - wx) <= MARKER_HIT_RADIUS && Math.abs(h.y - wy) <= MARKER_HIT_RADIUS) return { kind: 'hole', obj: h };
        }
        if (overlays.horses) {
            for (const h of activeItemsOfType(0)) if (Math.abs(h.x - wx) <= MARKER_HIT_RADIUS && Math.abs(h.y - wy) <= MARKER_HIT_RADIUS) return { kind: 'horse', obj: h };
        }
        return null;
    }

    
    
    
