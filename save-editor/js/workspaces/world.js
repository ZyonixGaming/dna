    async function loadXmlSprites(src) {
        const res = await fetch(src);
        if (!res.ok) throw new Error('Failed to load ' + src + ': HTTP ' + res.status);
        const text = await res.text();
        const xml = new DOMParser().parseFromString(text, 'text/xml');
        const out = {};
        xml.querySelectorAll('sprite').forEach((el) => {
            out[el.getAttribute('n')] = {
                x: parseFloat(el.getAttribute('x')), y: parseFloat(el.getAttribute('y')),
                w: parseFloat(el.getAttribute('w')), h: parseFloat(el.getAttribute('h')),
                hx: parseFloat(el.getAttribute('hx')) || 0, hy: parseFloat(el.getAttribute('hy')) || 0
            };
        });
        return out;
    }
    function computeAverageColors(img) {
        const c = document.createElement('canvas');
        c.width = img.width; c.height = img.height;
        const ctx = c.getContext('2d', { willReadFrequently: true });
        ctx.drawImage(img, 0, 0);
        const cols = Math.floor(img.width / TILE_PX), rows = Math.floor(img.height / TILE_PX);
        const colors = {};
        for (let ry = 0; ry < rows; ry++) {
            for (let rx = 0; rx < cols; rx++) {
                const data = ctx.getImageData(rx * TILE_PX, ry * TILE_PX, TILE_PX, TILE_PX).data;
                let r = 0, g = 0, b = 0, n = 0;
                for (let i = 0; i < data.length; i += 4) {
                    if (data[i + 3] === 0) continue;
                    r += data[i]; g += data[i + 1]; b += data[i + 2]; n++;
                }
                colors[rx * TILE_PX + ',' + ry * TILE_PX] = n ? [Math.round(r / n), Math.round(g / n), Math.round(b / n)] : [30, 30, 40];
            }
        }
        return colors;
    }
    
    
    
    
    
    
    
    
    
    
    
