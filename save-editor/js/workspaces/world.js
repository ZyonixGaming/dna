    function syncMinimap() {
        if (!doc || minimapTimer) return;
        if (doc.grid === minimapGrid && doc.grid.rev === minimapRev) return;
        minimapTimer = setTimeout(() => {
            minimapTimer = null;
            if (!doc) return;
            renderMinimap();
            renderMinimapViewbox();
        }, MINIMAP_REBUILD_MS);
    }

    function renderMinimap() {
        const canvas = document.getElementById('minimapCanvas');
        if (!doc) { canvas.width = 0; canvas.height = 0; minimapBase = null; minimapGrid = null; return; }
        const grid = doc.grid;
        minimapGrid = grid;
        minimapRev = grid.rev;
        const maxDim = 200;
        const scale = Math.min(1, maxDim / Math.max(grid.width, grid.height));
        const mw = Math.max(1, Math.round(grid.width * scale)), mh = Math.max(1, Math.round(grid.height * scale));
        canvas.width = grid.width; canvas.height = grid.height;
        canvas.style.width = mw + 'px'; canvas.style.height = mh + 'px';
        const ctx = canvas.getContext('2d');
        const imgData = ctx.createImageData(grid.width, grid.height);
        const colors = atlas.terrainColors || {};
        for (let y = 0; y < grid.height; y++) {
            for (let x = 0; x < grid.width; x++) {
                const t = grid.get(x, y);
                const rect = terrainSpriteRect(t.id, t.health);
                const c = colors[rect.sx + ',' + rect.sy] || [60, 60, 70];
                const idx = (y * grid.width + x) * 4;
                imgData.data[idx] = c[0]; imgData.data[idx + 1] = c[1]; imgData.data[idx + 2] = c[2]; imgData.data[idx + 3] = 255;
            }
        }
        minimapBase = imgData;
        ctx.putImageData(imgData, 0, 0);
    }
