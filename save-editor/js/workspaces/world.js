    function deleteSelection() {
        const sel = selection;
        if (!sel) return false;
        if (sel.kind === 'buried') { deleteBuriedItem(sel.obj); return true; }
        if (sel.kind === 'ground' || sel.kind === 'hole' || sel.kind === 'horse') {
            deleteWorldItemSel(sel.obj, sel.kind);
            return true;
        }
        return false;
    }

    function onKeyDown(e) {
        if (!doc || !isPaneActive()) return;
        if (e.ctrlKey || e.metaKey || e.altKey) return;
        const t = document.activeElement;
        if (t && /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName)) return;
        if (document.querySelector('.modal-backdrop.show')) return;

        const k = e.key.toLowerCase();
        if (TOOL_KEYS[k]) { e.preventDefault(); setTool(TOOL_KEYS[k]); return; }
        if (e.key === '[' || e.key === ']') {
            e.preventDefault();
            const at = BRUSH_SIZES.indexOf(brushSize);
            const next = BRUSH_SIZES[Math.min(BRUSH_SIZES.length - 1,
                Math.max(0, (at < 0 ? 0 : at) + (e.key === ']' ? 1 : -1)))];
            brushSize = next;
            const sizeSel = document.getElementById('brushSize');
            if (sizeSel) sizeSel.value = String(next);
            Toast.toast('Brush ' + next, 'info', 900);
            return;
        }
        if (e.key === 'Escape') { e.preventDefault(); selection = null; renderInspector(); scheduleRender(); return; }
        if (e.key === 'Delete' || e.key === 'Backspace') {
            if (deleteSelection()) e.preventDefault();
            return;
        }
        if (e.key === '0') { e.preventDefault(); setZoom('fit'); return; }
        if (e.key === '+' || e.key === '=') { e.preventDefault(); setZoom(Math.min(8, view.zoom * 2)); return; }
        if (e.key === '-' || e.key === '_') { e.preventDefault(); setZoom(Math.max(0.05, view.zoom / 2)); return; }
    }

