    function genomePatchSig(genomeOff) {
        if (!doc || doc.patches.size === 0) return 0;
        let s = 0;
        for (let i = 0; i < 240; i++) {
            const off = genomeOff + i;
            if (doc.patches.has(off)) s = (Math.imul(s, 33) + (i + 1) * 257 + doc.patches.get(off)) >>> 0;
        }
        return s;
    }

    
    function invalidateEditedHorseRenders() {
        if (!doc) return;
        for (const [genomeOff, entry] of horseRenderCache) {
            if (entry && entry.sig !== genomePatchSig(genomeOff)) horseRenderCache.delete(genomeOff);
        }
    }

    function renderHorseSprite(genomeOff) {
        const cached = horseRenderCache.get(genomeOff);
        if (cached !== undefined) return cached && cached.canvas;
        if (!window.HorseRender || !doc) return null;
        const sig = genomePatchSig(genomeOff);
        try {
            const HR = window.HorseRender;
            const alleles = new Array(240);
            for (let i = 0; i < 240; i++) {
                
                
                
                const b = effByte(genomeOff + i);
                const n1 = b % 8, n2 = (b - n1) / 8;
                alleles[i] = [n1 - 1, n2 - 1];
            }
            const geno = new HR.Genome.Genotype(alleles);
            const hash = HR.Genome.hash(alleles);
            const pheno = HR.Phenotype.build(geno);
            const colors = HR.Colors.build(geno, hash);
            const rig = HR.Rig.build(pheno, colors, hash);
            const offCanvas = document.createElement('canvas');
            HR.Render.render(offCanvas, rig, pheno, colors, hash, { zoom: 2, pad: 1 });
            horseRenderCache.set(genomeOff, { canvas: offCanvas, sig });
            return offCanvas;
        } catch (e) {
            horseRenderCache.set(genomeOff, { canvas: null, sig });
            return null;
        }
    }
    function clearHorseRenderCache() { horseRenderCache.clear(); }

    function drawDiamondMarker(ctx, wx, wy) {
        const s = 5;
        ctx.beginPath();
        ctx.moveTo(wx, wy - s); ctx.lineTo(wx + s, wy); ctx.lineTo(wx, wy + s); ctx.lineTo(wx - s, wy);
        ctx.closePath(); ctx.fill();
        ctx.strokeStyle = 'rgba(0,0,0,0.6)'; ctx.lineWidth = 1 / view.zoom; ctx.stroke();
    }

    function drawOverlayMarkers(ctx, viewRect) {
        if (!doc) return;
        const locs = atlas.locs;
        const inView = (x, y) => x >= viewRect.x0 - TILE_PX && x <= viewRect.x1 + TILE_PX && y >= viewRect.y0 - TILE_PX && y <= viewRect.y1 + TILE_PX;
        const labels = [];

        if (overlays.locations && locs) {
            for (const loc of mapSpaceMarkers()) {
                if (loc.value === 'Truck') continue;
                if (!inView(loc.x, loc.y)) continue;
                const rect = locsSpriteRect(loc.index);
                ctx.drawImage(locs.img, rect.sx, rect.sy, rect.sw, rect.sh, loc.x - TILE_PX / 2, loc.y - TILE_PX / 2, TILE_PX, TILE_PX);
                labels.push({ x: loc.x, y: loc.y - TILE_PX / 2, text: markerLabel(loc) });
            }
            const vial = doc.state.locationMarkers.find((l) => l.value === 'vial world');
            if (vial) {
                const vEdit = doc.locationEdits.get(vial.offset);
                const vx = vEdit ? vEdit.x : vial.x, vy = vEdit ? vEdit.y : vial.y;
                if (inView(vx, vy)) {
                    const rect = locsSpriteRect(vial.index);
                    ctx.drawImage(locs.img, rect.sx, rect.sy, rect.sw, rect.sh, vx, vy, TILE_PX, TILE_PX);
                    labels.push({ x: vx + TILE_PX / 2, y: vy, text: 'vial world' });
                }
            }
            const truck = doc.state.locationMarkers.find((l) => l.value === 'Truck');
            if (truck) {
                const edit = doc.locationEdits.get(truck.offset);
                const tx = edit ? edit.x : truck.x, ty = edit ? edit.y : truck.y;
                if (inView(tx, ty)) {
                    const rect = locsSpriteRect(truck.index);
                    ctx.drawImage(locs.img, rect.sx, rect.sy, rect.sw, rect.sh, tx - TILE_PX / 2, ty - TILE_PX / 2, TILE_PX, TILE_PX);
                    labels.push({ x: tx, y: ty - TILE_PX / 2, text: 'Truck' });
                }
            }
        }
        if (overlays.ground) {
            ctx.fillStyle = '#66d9ef';
            for (const g of activeItemsOfType(3)) {
                if (!inView(g.x, g.y)) continue;
                if (!drawItemSprite(ctx, g.index, g.x, g.y)) drawDiamondMarker(ctx, g.x, g.y);
                labels.push({ x: g.x, y: g.y - 6, text: (Items.ITEM_LIST[g.index] || {}).displayName || ('item ' + g.index) });
            }
        }
        if (overlays.holes) {
            ctx.fillStyle = '#5c3a1e';
            for (const h of activeItemsOfType(4)) if (inView(h.x, h.y)) drawDiamondMarker(ctx, h.x, h.y);
        }
        if (overlays.buried) {
            ctx.fillStyle = '#ffd966';
            for (const b of activeBuriedItems()) {
                if (!inView(b.x, b.y)) continue;
                
                
                
                const bx = b.x + TILE_PX / 2, by = b.y - TILE_PX / 2;
                ctx.save();
                ctx.globalAlpha = 0.55;
                if (!drawItemSprite(ctx, b.itemIndex, bx, by)) drawDiamondMarker(ctx, bx, by);
                ctx.restore();
                labels.push({ x: bx, y: by - 6, text: itemLabel(b.itemIndex) + ' (buried)' });
            }
        }
        if (overlays.horses) {
            for (const h of activeItemsOfType(0)) {
                if (!inView(h.x, h.y)) continue;
                let drawn = false;
                if (overlays.rendered && h.genomeOff != null) {
                    const sprite = renderHorseSprite(h.genomeOff);
                    if (sprite && sprite.width > 0) {
                        
                        
                        
                        
                        
                        
                        
                        const BOX = 20;
                        const s = BOX / Math.max(sprite.width, sprite.height);
                        const dw = sprite.width * s, dh = sprite.height * s;
                        
                        
                        
                        const reversed = h.detailOff != null && (effByte(h.detailOff + 14) & 0x01) !== 0;
                        ctx.save();
                        ctx.translate(h.x, h.y);
                        if (reversed) ctx.scale(-1, 1);
                        ctx.drawImage(sprite, -dw / 2, -dh / 2, dw, dh);
                        ctx.restore();
                        drawn = true;
                    }
                }
                if (!drawn) {
                    ctx.fillStyle = horseMarkerColor(h);
                    drawDiamondMarker(ctx, h.x, h.y);
                }
                const name = horseName(h);
                if (name) labels.push({ x: h.x, y: h.y - 6, text: name });
            }
        }
        if (overlays.labels && view.zoom >= 0.75) {
            ctx.save();
            ctx.font = Math.max(1, 11 / view.zoom) + 'px monospace';
            ctx.textAlign = 'center';
            ctx.lineWidth = Math.max(1, 3 / view.zoom);
            ctx.strokeStyle = 'rgba(0,0,0,0.85)';
            ctx.fillStyle = '#fff';
            for (const l of labels) { ctx.strokeText(l.text, l.x, l.y - 3); ctx.fillText(l.text, l.x, l.y - 3); }
            ctx.restore();
        }
    }

