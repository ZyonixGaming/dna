    function buildRecordEntry(opts) {
        opts = opts || {};
        const nameBytes = new TextEncoder().encode(opts.name || '');
        const fixed = opts.fixed || RECORD_FIXED_BLANK;
        if (fixed.length !== RECORD_FIXED_LEN) {
            throw new Error('A record’s fixed block is ' + RECORD_FIXED_LEN +
                ' bytes, got ' + fixed.length + '.');
        }
        const links = opts.links || [];
        const out = new Uint8Array(4 + nameBytes.length + RECORD_FIXED_LEN + 4 + 4 * links.length);
        const view = new DataView(out.buffer);
        writeU32(view, 0, nameBytes.length);
        out.set(nameBytes, 4);
        out.set(fixed, 4 + nameBytes.length);
        const lco = 4 + nameBytes.length + RECORD_FIXED_LEN;
        writeU32(view, lco, links.length);
        for (let k = 0; k < links.length; k++) writeU32(view, lco + 4 + 4 * k, links[k] >>> 0);
        return out;
    }

    
    function measureRecordEntry(rec) {
        const len = rec.length;
        const view = new DataView(rec.buffer, rec.byteOffset, rec.byteLength);
        if (len < 4) throw new Error('Record entry too short to hold a name length.');
        const nameLen = u32(view, 0, len);
        if (nameLen > 255) throw new Error('Implausible record name length ' + nameLen + '.');
        const lco = 4 + nameLen + RECORD_FIXED_LEN;
        if (lco + 4 > len) throw new Error('Record entry truncated before its link count.');
        const linkCount = u32(view, lco, len);
        if (linkCount > 4096) throw new Error('Implausible offspring-link count ' + linkCount + '.');
        return lco + 4 + 4 * linkCount;
    }

    
